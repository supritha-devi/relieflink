-- ReliefLink Stage 7: request status history and transaction-safe status tracking.
-- Run once after stage6_supplies.sql.

CREATE TABLE IF NOT EXISTS request_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES request(request_id) ON DELETE CASCADE,
    old_status TEXT CHECK (old_status IN ('Pending', 'Dispatched', 'Delivered')),
    new_status TEXT NOT NULL CHECK (new_status IN ('Pending', 'Dispatched', 'Delivered')),
    changed_by INTEGER REFERENCES user_account(user_id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION record_request_status_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_actor_id INTEGER;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status THEN
        RETURN NEW;
    END IF;

    v_actor_id := NULLIF(current_setting('relieflink.user_id', TRUE), '')::INTEGER;
    IF v_actor_id IS NULL THEN
        v_actor_id := NEW.requested_by;
    END IF;

    INSERT INTO request_status_history
        (request_id, old_status, new_status, changed_by)
    VALUES (
        NEW.request_id,
        CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
        NEW.status,
        v_actor_id
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS request_status_history_trigger ON request;
CREATE TRIGGER request_status_history_trigger
AFTER INSERT OR UPDATE OF status ON request
FOR EACH ROW EXECUTE FUNCTION record_request_status_history();

CREATE INDEX IF NOT EXISTS request_status_history_request_time_idx
    ON request_status_history (request_id, changed_at);

