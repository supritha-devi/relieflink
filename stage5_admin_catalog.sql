-- ReliefLink Stage 5: disasters, places, affected areas, camps and contacts.
-- Run once in relief_db after stage4_staff.sql.

CREATE TABLE IF NOT EXISTS local_contact (
    local_contact_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id INTEGER NOT NULL REFERENCES region(region_id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    contact_type TEXT NOT NULL CHECK (contact_type IN ('Person', 'Group')),
    phone_number TEXT NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Allow transaction-local actor attribution for admin catalog audit triggers.
CREATE OR REPLACE FUNCTION log_relief_activity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_row JSONB;
    v_record_id INTEGER;
    v_actor_id INTEGER;
BEGIN
    v_row := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
    v_actor_id := NULLIF(current_setting('relieflink.user_id', TRUE), '')::INTEGER;

    CASE TG_TABLE_NAME
        WHEN 'request' THEN
            v_record_id := (v_row ->> 'request_id')::INTEGER;
            v_actor_id := COALESCE(v_actor_id, (v_row ->> 'requested_by')::INTEGER);
        WHEN 'donation' THEN
            v_record_id := (v_row ->> 'donation_id')::INTEGER;
            IF v_actor_id IS NULL THEN
                SELECT user_id INTO v_actor_id FROM donor
                 WHERE donor_id = (v_row ->> 'donor_id')::INTEGER;
            END IF;
        WHEN 'shipment' THEN
            v_record_id := (v_row ->> 'shipment_id')::INTEGER;
        WHEN 'message' THEN
            v_record_id := (v_row ->> 'message_id')::INTEGER;
            v_actor_id := COALESCE(v_actor_id, (v_row ->> 'sender_user_id')::INTEGER);
        WHEN 'call_log' THEN
            v_record_id := (v_row ->> 'call_id')::INTEGER;
            v_actor_id := COALESCE(v_actor_id, (v_row ->> 'logged_by')::INTEGER);
        WHEN 'user_account' THEN
            v_record_id := (v_row ->> 'user_id')::INTEGER;
        WHEN 'helpline' THEN
            v_record_id := (v_row ->> 'helpline_id')::INTEGER;
        WHEN 'disaster_area' THEN
            v_record_id := (v_row ->> 'disaster_id')::INTEGER;
        WHEN 'disaster' THEN
            v_record_id := (v_row ->> 'disaster_id')::INTEGER;
        WHEN 'region' THEN
            v_record_id := (v_row ->> 'region_id')::INTEGER;
        WHEN 'camp' THEN
            v_record_id := (v_row ->> 'camp_id')::INTEGER;
        WHEN 'local_contact' THEN
            v_record_id := (v_row ->> 'local_contact_id')::INTEGER;
        ELSE
            RAISE EXCEPTION 'Activity logging is not configured for table %', TG_TABLE_NAME;
    END CASE;

    INSERT INTO activity_log (user_id, action, table_name, record_id)
    VALUES (v_actor_id, lower(TG_OP) || '_' || TG_TABLE_NAME, TG_TABLE_NAME, v_record_id);

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS log_disaster_activity ON disaster;
CREATE TRIGGER log_disaster_activity
AFTER INSERT OR UPDATE OR DELETE ON disaster
FOR EACH ROW EXECUTE FUNCTION log_relief_activity();

DROP TRIGGER IF EXISTS log_region_activity ON region;
CREATE TRIGGER log_region_activity
AFTER INSERT OR UPDATE OR DELETE ON region
FOR EACH ROW EXECUTE FUNCTION log_relief_activity();

DROP TRIGGER IF EXISTS log_camp_activity ON camp;
CREATE TRIGGER log_camp_activity
AFTER INSERT OR UPDATE OR DELETE ON camp
FOR EACH ROW EXECUTE FUNCTION log_relief_activity();

DROP TRIGGER IF EXISTS log_local_contact_activity ON local_contact;
CREATE TRIGGER log_local_contact_activity
AFTER INSERT OR UPDATE OR DELETE ON local_contact
FOR EACH ROW EXECUTE FUNCTION log_relief_activity();
